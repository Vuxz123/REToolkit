import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createToolkit} from '../src/toolkit.js';
import {createUnityFixture} from './fixtures/unity-export-fixture.mjs';
import {runAssetOperation} from '../src/assets/service.js';
import {inspectAssetReadiness} from '../src/assets/readiness.js';

test('shared service indexes export, maps scripts and fills a stub with unchanged scene/meta',async t=>{
  const root=fs.mkdtempSync(path.join(os.tmpdir(),'retk-assets-service-'));t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
  const toolkit=createToolkit(root,{log:()=>{}});await toolkit.init('Game');
  const input=path.join(toolkit.workspace('Game'),'01_Extracted');
  fs.writeFileSync(path.join(input,'libil2cpp.so'),'native');fs.writeFileSync(path.join(input,'global-metadata.dat'),'metadata');await toolkit.scan('Game',input);
  const fixture=await createUnityFixture(path.join(toolkit.workspace('Game'),'05_ReconstructedSource'));
  const project=toolkit.read('Game');project.reconstructedSourceDir=fixture.projectDir;toolkit.save('Game',project);
  const indexed=await runAssetOperation(toolkit,'Game','assets.index',{graphMaxMiB:512});assert.equal(indexed.state,'indexed');
  assert.equal(toolkit.read('Game').assetReconstruction.graphLimitBytes,512*1024**2);
  await assert.rejects(runAssetOperation(toolkit,'Game','assets.index',{graphMaxMiB:513}));
  assert.equal(toolkit.read('Game').assetReconstruction.graph,'ready');
  assert.equal((await inspectAssetReadiness(toolkit,'Game')).state,'indexed');
  const scripts=await runAssetOperation(toolkit,'Game','assets.scripts');assert.equal(scripts.items[0].identity.fullName,'Demo.Player');
  const source=await runAssetOperation(toolkit,'Game','assets.source',{id:scripts.items[0].scriptId});
  assert.equal(source.source,fixture.source);assert.equal(source.dataTrust,'untrusted-target-content');
  const scene=fs.readFileSync(fixture.scenePath),meta=fs.readFileSync(fixture.scriptPath+'.meta');
  const request={kind:'retoolkit-reconstruction-request',schemaVersion:1,graphRevision:indexed.revision,changes:[{scriptId:scripts.items[0].scriptId,source:fixture.source.replace('string text = "{ }";','health += 1;')}]};
  const plan=await runAssetOperation(toolkit,'Game','reconstruct.plan',{request});
  const saved=JSON.parse(fs.readFileSync(path.join(toolkit.workspace('Game'),plan.storedPlan),'utf8'));assert.ok(saved.graph.assets.every(a=>a.script));assert.ok(saved.graph.nodes.every(n=>n.scriptRef&&!n.fields));
  const receipt=await runAssetOperation(toolkit,'Game','reconstruct.apply',{operationId:plan.operationId});assert.equal(receipt.compileReady,false);
  assert.equal(Object.hasOwn(receipt,'files'),false);
  assert(fs.existsSync(path.join(toolkit.workspace('Game'),receipt.storedReceipt)));
  assert.equal(toolkit.read('Game').assetReconstruction.state,'source_applied');
  const refreshed=JSON.parse(fs.readFileSync(path.join(toolkit.workspace('Game'),'04_Notes/assets/graph.json'),'utf8'));assert.equal(refreshed.profile.limits.maxGraphBytes,512*1024**2);
  assert.deepEqual(fs.readFileSync(fixture.scenePath),scene);assert.deepEqual(fs.readFileSync(fixture.scriptPath+'.meta'),meta);
  assert.equal((await runAssetOperation(toolkit,'Game','reconstruct.verify',{operationId:plan.operationId})).valid,true);
  const {graphRefresh:retryRefresh,...retryReceipt}=await runAssetOperation(toolkit,'Game','reconstruct.apply',{operationId:plan.operationId}),{graphRefresh:firstRefresh,...firstReceipt}=receipt;
  assert.deepEqual(retryReceipt,firstReceipt);assert.equal(retryRefresh.strategy,'reuse');assert.equal(firstRefresh.strategy,'source-refresh');
  const noEditor=toolkit.read('Game');noEditor.unityEditorPath=path.join(root,'missing/Unity.exe');toolkit.save('Game',noEditor);
  const validation=await runAssetOperation(toolkit,'Game','reconstruct.validate',{timeoutSeconds:5});assert.equal(validation.state,'blocked');assert.equal(validation.code,'unity_editor_missing');
  assert.equal((await runAssetOperation(toolkit,'Game','reconstruct.validation',{operationId:validation.operationId})).compileReady,false);
  fs.writeFileSync(path.join(input,'extra.assets'),'drift');
  assert.equal((await inspectAssetReadiness(toolkit,'Game')).state,'stale');
  await assert.rejects(runAssetOperation(toolkit,'Game','assets.list'),{code:'stale_graph'});
  await assert.rejects(runAssetOperation(toolkit,'Game','arbitrary.exec'),{code:'asset_method_invalid'});
});
