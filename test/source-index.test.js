import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fixture} from './reconstruction-fixture.js';
import {createToolkit} from '../src/toolkit.js';
import {invokeAssetApi} from '../src/assets/api.js';
import {inspectAssetReadiness} from '../src/assets/readiness.js';
import {buildDesktopCommand} from '../src/desktop/operations.js';

test('source-only discovery, body apply and verify do not parse assets or build a full graph',async t=>{
 const f=await fixture(t),toolkit=createToolkit(f.root,{log:()=>{}});await toolkit.init('Game');
 const workspace=toolkit.workspace('Game'),input=path.join(workspace,'01_Extracted');
 fs.writeFileSync(path.join(input,'libil2cpp.so'),'native');fs.writeFileSync(path.join(input,'global-metadata.dat'),'metadata');await toolkit.scan('Game',input);
 const project=path.join(workspace,'05_ReconstructedSource');fs.cpSync(f.projectDir,project,{recursive:true});
 fs.writeFileSync(path.join(project,'ProjectSettings/ProjectVersion.txt'),'m_EditorVersion: 2022.3.62f2\n');
 fs.writeFileSync(path.join(project,'Assets/Main.unity'),'%YAML 1.1\n--- !u!114 &1\nMonoBehaviour:\n  health: [\n');
 const call=(method,params={})=>invokeAssetApi(toolkit,'Game',method,params);
 const indexed=await call('assets.index',{scope:'source'});assert.equal(indexed.state,'source_indexed');
 assert.deepEqual(buildDesktopCommand('assets.source-index',{name:'Game'}),['assets','index','Game','--scope','source']);
 const readiness=await inspectAssetReadiness(toolkit,'Game');assert.equal(readiness.sourceIndex.state,'ready');assert.equal(readiness.bindingsVerified,false);assert.notEqual(readiness.state,'indexed');
 const scripts=await call('assets.scripts'),script=scripts.items.find(v=>v.path==='Assets/Player.cs');
 assert.equal(script.state.bindings,'unverified');assert.equal(script.traversalComplete,false);
 assert.equal(script.sourceCapabilities.bodyReplacement.state,'requires-plan-validation');
 const source=await call('assets.source',{id:script.scriptId});
 assert(!fs.existsSync(path.join(workspace,'04_Notes/assets/graph.json')));
 const request={kind:'retoolkit-reconstruction-request',schemaVersion:1,graphRevision:scripts.revision,changes:[{scriptId:script.scriptId,mode:'bodies',source:source.source+'\n// body route\n'}]};
 const plan=await call('reconstruct.plan',{request});
 const invalidContract={...request,changes:[{...request.changes[0],source:source.source.replace('int health','float health')}]};
 await assert.rejects(call('reconstruct.plan',{request:invalidContract}),/contract|declaration/);
 const applied=await call('reconstruct.apply',{operationId:plan.operationId});
 assert.equal(applied.graphRefresh.strategy,'source-index');assert.equal(applied.bindingsVerified,false);
 assert.equal((await call('reconstruct.verify',{operationId:plan.operationId})).valid,true);
 assert.equal((await call('reconstruct.apply',{operationId:plan.operationId})).graphRefresh.strategy,'source-index');
 assert(!fs.existsSync(path.join(workspace,'04_Notes/assets/graph.json')));
 assert.equal(fs.readFileSync(path.join(project,'Assets/Main.unity'),'utf8'),'%YAML 1.1\n--- !u!114 &1\nMonoBehaviour:\n  health: [\n');
 const next=await call('assets.scripts');assert.notEqual(next.revision,scripts.revision);
 await assert.rejects(call('reconstruct.plan',{request}),/revision/);
 await assert.rejects(call('assets.refs',{id:script.scriptId}));
 const legacy={...request,graphRevision:next.revision,changes:[{scriptId:script.scriptId,source:source.source}]};
 await assert.rejects(call('reconstruct.plan',{request:legacy}),/explicit.*mode/i);
 const sourceFile=path.join(workspace,'04_Notes/assets/source-index.json');
 fs.unlinkSync(sourceFile);
 assert.equal((await call('assets.scripts')).revision,next.revision);
 assert(fs.existsSync(sourceFile));
 await assert.rejects(call('assets.index',{scope:'full'}));
 assert(fs.existsSync(sourceFile),'failed full indexing must preserve the code route');
 fs.appendFileSync(path.join(project,'Assets/Main.unity'),' changed');
 assert.equal((await call('reconstruct.verify',{operationId:plan.operationId})).valid,false);
 fs.writeFileSync(path.join(project,'Assets/Main.unity'),f.files['Assets/Main.unity']);
 const full=await call('assets.index',{scope:'full'});assert.equal(full.state,'indexed');
 assert(!fs.existsSync(sourceFile));assert.equal((await call('assets.scripts')).items[0].state.bindings,'resolved');
});
